"""The supporting table the paper promises: both statistical readings, every arm
comparison.

The main text says that whichever of the two tests is the permissive one depends
on the test set's size relative to the subset-to-subset spread, and that the two
readings disagree three times. A reader cannot check either claim from the main
tables, which report only the test we rely on. This writes the other one beside
it for every comparison we ran at the three-subset protocol, including the cells
the criterion excludes.

The arithmetic is the same code the main tables use -- `kdstore.stats` is pure
Python and is loaded directly here, so this script runs without torch and
without a GPU.

    python code/11_s1_table/make_s1.py

This script needs the per-item correctness vectors that the McNemar test is
computed from. Those are not in the released archive, which carries per-run
accuracies only, so the built output ships instead as figures/S1_Table.tex
and figures/S1_Table.pdf.
"""
import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location(
    "kdstats", ROOT / "code" / "kdstore" / "stats.py")
S = importlib.util.module_from_spec(spec)
spec.loader.exec_module(S)

CONFIG = ROOT / "code" / "05_results" / "config.json"
OUT = (ROOT / "paper" if (ROOT / "paper").is_dir() else ROOT / "figures") / "S1_Table.tex"


class Results:
    """Same lookup rule as the main table script: tag, with or without prefix."""

    def __init__(self, directory):
        self.directory = Path(directory)
        self._cache = {}

    def get(self, tag):
        if tag not in self._cache:
            for name in (f"grid_{tag}.json", f"{tag}.json"):
                path = self.directory / name
                if path.exists():
                    break
            else:
                raise FileNotFoundError(f"no result file for tag {tag!r}")
            self._cache[tag] = json.loads(path.read_text())
        return self._cache[tag]

    def accuracy(self, tag):
        return self.get(tag)["acc"] * 100

    def flags(self, tag):
        return [bool(g["ok"]) for g in self.get(tag).get("gens", [])]


def rows_for(config, results):
    rows = []
    for name, cell in config["cells"].items():
        arms = cell.get("arms", {})
        pairs = []
        if "text" in arms and "artifact" in arms:
            pairs.append(("artifact $-$ text", arms["artifact"], arms["text"]))
        if "lowgate" in arms:
            pairs.append(("artifact $-$ low gate", arms["artifact"],
                          arms["lowgate"]))
            pairs.append(("low gate $-$ text", arms["lowgate"], arms["text"]))

        qualified = S.qualifies(cell["base"], cell["full_corpus"],
                                config["eval_size"][cell["dataset"]])
        for label, a_tags, b_tags in pairs:
            differences, b_total, c_total = [], 0, 0
            for a_tag, b_tag in zip(a_tags, b_tags):
                differences.append(results.accuracy(a_tag)
                                   - results.accuracy(b_tag))
                a_flags, b_flags = results.flags(a_tag), results.flags(b_tag)
                if a_flags and b_flags:
                    x, y = S.discordant(a_flags, b_flags)
                    b_total += x
                    c_total += y
            paired = S.paired_t_test(differences)
            pooled = S.mcnemar(b_total, c_total)
            agree = (paired["p"] < 0.05) == (pooled["p"] < 0.05)
            rows.append({
                "cell": name, "comparison": label,
                "dataset": cell["dataset"],
                "qualified": bool(qualified["qualified"]),
                "effect": paired["mean"], "sd": paired["sd"],
                "t": paired["t"], "subset_p": paired["p"],
                "b": b_total, "c": c_total, "mcnemar_p": pooled["p"],
                "agree": agree,
            })
    return rows


def fmt_p(p):
    if p < 0.001:
        return "$<$0.001"
    return f"{p:.3f}"


def main():
    config = json.loads(CONFIG.read_text())
    results = Results(ROOT / config["results_dir"])
    rows = rows_for(config, results)
    disagree = [r for r in rows if not r["agree"]]

    lines = [
        r"% Generated by code/11_s1_table/make_s1.py, do not edit by hand.",
        r"\documentclass[10pt]{article}",
        r"\usepackage[margin=2cm,landscape,a4paper]{geometry}",
        r"\usepackage{booktabs}",
        r"\usepackage{amsmath}",
        r"\pagestyle{empty}",
        r"\begin{document}",
        r"\noindent\textbf{S1 Table. Both statistical readings for every "
        r"subset-paired arm comparison.}",
        r"",
        r"\noindent Each row is one arm comparison at the three-subset "
        r"protocol. $\Delta$ is the mean difference in accuracy over the three "
        r"subsets, in points, with the subset-to-subset standard deviation "
        r"beside it; the paired $t$-test on those three differences "
        r"($\mathrm{df}=2$) is the test the paper reports. $b$ and $c$ count "
        r"discordant test items pooled over the three subsets, items the "
        r"first arm got right and the second wrong, and the reverse, and the "
        r"McNemar $p$ is computed from them. Pooling reuses the same test "
        r"items three times, which is why we do not rely on it. Cells marked "
        r"\emph{excluded} fail the headroom criterion of the main text and are "
        r"reported here for completeness.",
        r"",
        r"\vspace{1em}",
        r"\noindent\begin{tabular}{llrrrrrrrl}",
        r"\toprule",
        r"cell & comparison & $\Delta$ & sd & $t$ & $p$ & $b$ & $c$ & "
        r"McNemar $p$ & readings \\",
        r"\midrule",
    ]
    last = None
    for r in rows:
        cell = r["cell"] + ("" if r["qualified"] else r" \emph{(excluded)}")
        shown = "" if cell == last else cell
        last = cell
        lines.append(
            f"{shown} & {r['comparison']} & {r['effect']:+.2f} & "
            f"{r['sd']:.2f} & {r['t']:+.2f} & {fmt_p(r['subset_p'])} & "
            f"{r['b']} & {r['c']} & {fmt_p(r['mcnemar_p'])} & "
            + ("agree" if r["agree"] else r"\textbf{disagree}") + r" \\")
    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        r"",
        r"\vspace{1em}",
        r"\noindent The two readings disagree on "
        f"{len(disagree)} of {len(rows)} comparisons"
        + (": " + "; ".join(f"{r['cell']}, {r['comparison']}" for r in disagree)
           if disagree else "") + ".",
        r"\end{document}",
    ]
    OUT.write_text("\n".join(lines) + "\n")

    print(f"{len(rows)} comparisons, {len(disagree)} disagreements")
    for r in disagree:
        print(f"  {r['cell']:24s} {r['comparison']:22s} "
              f"subset p={r['subset_p']:.4f}  McNemar p={r['mcnemar_p']:.4f}")
    only_mcnemar = [r for r in disagree
                    if r["mcnemar_p"] < 0.05 <= r["subset_p"]]
    print(f"  of those, {len(only_mcnemar)} are McNemar-significant only")
    print(f"written {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
